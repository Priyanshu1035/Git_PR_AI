import path from "node:path";
import { config } from "../config.js";
import * as gh from "./github.js";
import { addRemote, cloneRepo, removeWorkspace } from "./repo.js";
import { decidePushStrategy } from "./push-target.js";
import { createSandbox } from "./sandbox.js";
import { createToolbox } from "./tools.js";
import { runAgent } from "./agent.js";
import { flushTelemetry, runTracked, traceStep } from "../telemetry.js";
import { checkChangedFiles, checkIssueLabel, checkPullRequestLabel, describe, PR_LABEL } from "../guardrails/rules.js";

// Run a guardrail as a traced Failproof step (hook_triggered / hook_completed).
const gate = (name, check) => traceStep(`guardrail:${name}`, async () => check(), (r) => (r.allowed ? "success" : "failed"));

async function pushWithRetry(git, remote, branch) {
  try {
    await git.push(remote, branch, ["--set-upstream"]);
  } catch {
    await new Promise((r) => setTimeout(r, 5000)); // a fresh fork can take a moment to accept pushes
    await git.push(remote, branch, ["--set-upstream"]);
  }
}

const oneLine = (s, max = 72) => String(s).replace(/\s+/g, " ").trim().slice(0, max);

// How each pipeline result is reported to Failproof AI.
const OUTCOME = { pr_opened: "success", cannot_fix: "rejected", tests_failed: "failed", no_changes: "failed", incomplete: "failed" };

function buildPrBody({ issue, summary, files, tests }) {
  const testLine =
    tests.passed === null
      ? "No test command detected for this repository."
      : tests.passed
        ? "✅ Tests passed."
        : "⚠️ Tests did **not** pass. Review carefully.";

  return `Fixes #${issue.number}

## Summary
${summary}

## Files changed
${files.map((f) => `- \`${f}\``).join("\n")}

## Validation
${testLine}

---
> 🤖 Generated by Git_PR AI and opened as a **draft**. A human must review before merging.`;
}

export async function runFixJob(job, log) {
  const [owner, repo] = job.repo.split("/");
  const n = job.issueNumber;
  const workdir = path.join(config.workdir, job.id);

  try {
    log(`Fetching issue #${n} from ${job.repo}`);
    const issue = await gh.getIssue(owner, repo, n);
    const { defaultBranch: baseBranch, canPush } = await gh.getRepoInfo(owner, repo);
    const strategy = decidePushStrategy({ canPush, mode: config.forkMode }); // fails fast if impossible

    log(`Cloning ${job.repo}@${baseBranch}`);
    const git = await cloneRepo({ owner, repo, branch: baseBranch, dest: workdir });
    const branch = `ai-fix/issue-${n}-${Date.now().toString(36)}`;
    await git.checkoutLocalBranch(branch);

    const sandbox = createSandbox(workdir, log);
    const toolbox = createToolbox({ repoPath: workdir, sandbox, log });

    // Everything from here on is one Failproof session, keyed by the job id.
    return await runTracked(
      {
        sessionId: job.id,
        goal: `Fix ${job.repo}#${n}: ${issue.title}`,
        fields: { fw_repo: job.repo, fw_issue: n },
      },
      async (run) => {
        const done = (result) => {
          run.setOutcome(OUTCOME[result.status] ?? "failed", result.summary);
          return result;
        };

        const labelGate = await gate("ai-label-required", () => checkIssueLabel(issue.labels, config.triggerLabel));
        if (!labelGate.allowed) {
          log(`Guardrail blocked run: ${describe(labelGate.violations)}`);
          await gh.commentOnIssue(
            owner, repo, n,
            `🤖 **Git_PR AI** will only work on issues labeled \`${config.triggerLabel}\`. Add the label and retry.`
          );
          return done({ status: "cannot_fix", summary: describe(labelGate.violations) });
        }

        log("Starting agent");
        const stats = await runAgent({ issue, repoFullName: job.repo, toolbox, log });
        const outcome = toolbox.state.finished;

        if (!outcome) return done({ status: "incomplete", ...stats });

        if (outcome.status === "cannot_fix") {
          await gh.commentOnIssue(
            owner, repo, n,
            `🤖 **Git_PR AI** investigated this issue but could not produce a safe fix.\n\n${outcome.summary}`
          );
          return done({ status: "cannot_fix", summary: outcome.summary, ...stats });
        }

        const files = [...toolbox.changedFiles];
        if (files.length === 0) return done({ status: "no_changes", summary: outcome.summary, ...stats });

        // Guardrail: re-check everything the agent touched before it can be committed.
        const fileGate = await gate("protected-files", () => checkChangedFiles(files));
        if (!fileGate.allowed) {
          log(`Guardrail blocked commit: ${describe(fileGate.violations)}`);
          await gh.commentOnIssue(
            owner, repo, n,
            `🤖 **Git_PR AI** produced changes that violate repository guardrails, so no PR was opened.\n\n${describe(fileGate.violations)}`
          );
          return done({ status: "cannot_fix", summary: describe(fileGate.violations), files, ...stats });
        }

        // Final validation, since the last edit may have come after the last run_tests call.
        const tests = sandbox.hasTests
          ? await traceStep("final_tests", () => sandbox.runTests(), (r) => (r.passed === false ? "failed" : "success"))
          : { passed: null, output: "" };

        if (tests.passed === false && config.requireGreenTests) {
          await gh.commentOnIssue(
            owner, repo, n,
            `🤖 **Git_PR AI** proposed a fix but the tests still failed, so no PR was opened.\n\n${outcome.summary}\n\n<details><summary>Test output</summary>\n\n\`\`\`\n${tests.output.slice(-3000)}\n\`\`\`\n</details>`
          );
          return done({ status: "tests_failed", summary: outcome.summary, files, ...stats });
        }

        // Stage only files the agent touched, so install artifacts like node_modules never leak in.
        await git.add(files);
        const status = await git.status();
        if (status.staged.length === 0) return done({ status: "no_changes", summary: outcome.summary, ...stats });

        await git.commit(`fix: ${oneLine(issue.title)} (#${n})`);

        const pr = await traceStep("open_pr", async () => {
          let remote = "origin";
          let head = branch;
          if (strategy === "fork") {
            log("Pushing to a fork of the repository");
            const fork = await gh.ensureFork(owner, repo);
            await addRemote(git, "fork", fork.owner, fork.repo);
            remote = "fork";
            head = `${fork.owner}:${branch}`;
          }
          await pushWithRetry(git, remote, branch);

          const created = await gh.createPullRequest({
            owner, repo, head, base: baseBranch,
            title: `Fix: ${oneLine(issue.title, 80)}`,
            body: buildPrBody({ issue, summary: outcome.summary, files, tests }),
          });
          await gh.addLabels(owner, repo, created.number, ["ai-generated"]);
          await gh.commentOnIssue(owner, repo, n, `🤖 **Git_PR AI** opened a draft PR for review: ${created.url}`);
          return created;
        });

        // Verify what GitHub actually recorded, not what we think we pushed.
        const prGate = await gate("pr-verify", async () => {
          const [prFiles, prLabels] = await Promise.all([
            gh.listPullRequestFiles(owner, repo, pr.number),
            gh.getPullRequestLabels(owner, repo, pr.number),
          ]);
          const f = checkChangedFiles(prFiles);
          const l = checkPullRequestLabel(prLabels, PR_LABEL);
          return { allowed: f.allowed && l.allowed, violations: [...f.violations, ...l.violations] };
        });
        if (!prGate.allowed) {
          log(`Guardrail closed PR: ${describe(prGate.violations)}`);
          await gh.closePullRequest(owner, repo, pr.number, `🤖 **Git_PR AI** closed this PR automatically: ${describe(prGate.violations)}`);
          return done({ status: "cannot_fix", summary: describe(prGate.violations), files, ...stats });
        }

        log(`Opened draft PR ${pr.url}`);
        return done({
          status: "pr_opened", prUrl: pr.url, fromFork: strategy === "fork",
          summary: outcome.summary, files, testsPassed: tests.passed, ...stats,
        });
      }
    );
  } finally {
    await flushTelemetry();
    await removeWorkspace(workdir).catch(() => {});
  }
}
